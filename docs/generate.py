        owners = [d for d in decls if d.kind in ("class", "enum class", "object", "companion object", "interface")]
        top_members = [d for d in decls if d.owner is None and d not in owners]
        if top_members:
            out += ["", "### Top-level declarations", "", table(["Kind", "Declaration"], [[d.kind, code(d.head)] for d in top_members if d.exported])]
