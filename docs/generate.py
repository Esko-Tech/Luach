def write_if_changed(path, content):
    full = os.path.join(ROOT, path)
    old = None
    if os.path.exists(full):
        with open(full, "r", encoding="utf-8") as f:
            old = f.read()
    if old == content:
        return False
    os.makedirs(os.path.dirname(full), exist_ok=True)
    with open(full, "w", encoding="utf-8") as f:
        f.write(content)
    return True


def apply_regions(path, generators, paths):
    text = read_text(path)
    found = {}
    for m in REGION_RE.finditer(text):
        name = m.group(1)
        if name in found:
            raise SystemExit(f"{path}: region {name} appears twice")
        found[name] = m
    unknown = set(found) - set(generators)
    missing = set(generators) - set(found)
    if unknown:
        raise SystemExit(f"{path}: unknown generated region(s) {sorted(unknown)}")
    if missing:
        raise SystemExit(f"{path}: missing generated region(s) {sorted(missing)}")

    def replace(m):
        name = m.group(1)
        body = generators[name](paths)
        open_marker = f"<!-- generated:{name} - written by docs/generate.py; to change it, edit the generator -->"
        return f"{open_marker}\n\n{body}\n\n<!-- /generated:{name} -->"

    new_text = REGION_RE.sub(replace, text)
    return write_if_changed(path, new_text)


def generate_once():
    paths = project_files()
    changed = []
    for path, generator in GENERATED_FILES.items():
        if write_if_changed(path, generator(paths)):
            changed.append(path)
    for path, generators in REGION_DOCS.items():
        if not os.path.exists(os.path.join(ROOT, path)):
            raise SystemExit(f"{path} does not exist")
        if apply_regions(path, generators, paths):
            changed.append(path)
    return changed


def main():
    all_changed = []
    for _ in range(8):
        changed = generate_once()
        all_changed.extend(changed)
        if not changed:
            break
    else:
        raise SystemExit("the generated docs did not reach a fixed point")
    for path in sorted(set(all_changed)):
        print(f"updated {path}")
    if not all_changed:
        print("docs already up to date")
    if not HAVE_YAML:
        print("note: PyYAML is not installed; workflow tables were skipped", file=sys.stderr)


if __name__ == "__main__":
    main()
