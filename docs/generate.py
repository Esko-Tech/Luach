def sh(*args):
    return subprocess.check_output(args, cwd=ROOT).decode()


def project_files():
    out = sh("git", "ls-files", "-z", "--cached", "--others", "--exclude-standard")
    paths = sorted(set(p for p in out.split("\0") if p))
    return [p for p in paths if os.path.isfile(os.path.join(ROOT, p))]


def read_bytes(path):
    with open(os.path.join(ROOT, path), "rb") as f:
        return f.read()


def read_text(path):
    return read_bytes(path).decode("utf-8", "replace")


def is_binary(data):
    return b"\x00" in data


def nr_lines(data):
    if not data:
        return 0
    n = data.count(b"\n")
    if not data.endswith(b"\n"):
        n += 1
    return n


def size_field(path):
    data = read_bytes(path)
    if is_binary(data):
        return f"{len(data)} bytes"
    return f"{nr_lines(data)} lines"


def ext_of(path):
    name = os.path.basename(path)
    if name.startswith("."):
        rest = name[1:]
        return "." + rest.rsplit(".", 1)[1] if "." in rest else "[none]"
    return "." + name.rsplit(".", 1)[1] if "." in name else "[none]"


def code(text):
    return "`" + str(text).replace("|", "\\|") + "`"


def table(headers, rows, align=None):
    align = align or ["---"] * len(headers)
    out = ["| " + " | ".join(headers) + " |", "| " + " | ".join(align) + " |"]
    for row in rows:
        out.append("| " + " | ".join(str(c) for c in row) + " |")
    return "\n".join(out)


def strip_literals(line):
    return STRING_RE.sub(lambda m: '""' if m.group(0).startswith('"') else "''", line)


def paren_balance(text):
    return text.count("(") - text.count(")")


def balanced(text, open_index):
    depth = 0
    for i in range(open_index, len(text)):
        c = text[i]
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return text[open_index + 1:i]
    return text[open_index + 1:]


def brace_block(text, open_index):
    depth = 0
    for i in range(open_index, len(text)):
        c = text[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return text[open_index + 1:i]
    return text[open_index + 1:]


def set_calls(block):
    result = {}
    for m in re.finditer(r"(\w+)\.set\(", block):
        value = balanced(block, m.end() - 1)
        strings = re.findall(r'"((?:\\.|[^"\\])*)"', value)
        result.setdefault(m.group(1), []).append("".join(strings) if strings else collapse(value))
    return result


def yaml_scalar(value):
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value).strip().replace("\n", " ")


def cut_head(statement):
    depth = 0
    angle = 0
    for i, c in enumerate(statement):
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        elif c == "<":
            angle += 1
        elif c == ">":
            angle -= 1
        elif depth == 0 and angle <= 0 and c in "{=":
            if c == "=" and i + 1 < len(statement) and statement[i + 1] == "=":
                continue
            return statement[:i].strip(), statement[i + 1:].strip() if c == "=" else None
    return statement.strip(), None


def collapse(text):
    text = re.sub(r"\s+", " ", text).strip()
    text = re.sub(r"\(\s+", "(", text)
    text = re.sub(r"\s+,", ",", text)
    text = re.sub(r",\s*\)", ")", text)
    return text


class Decl:
    def __init__(self, kind, name, head, modifiers, owner, line):
        self.kind = kind
        self.name = name
        self.head = head
        self.modifiers = modifiers
        self.owner = owner
        self.line = line
        self.definition = None
        self.block = False
        self.entries = []
        self.children = []

    @property
    def visibility(self):
        for v in ("private", "internal", "protected"):
            if v in self.modifiers:
                return v
        return "public"

    @property
    def exported(self):
        d = self
        while d is not None:
            if d.visibility in ("private", "internal"):
                return False
            d = d.owner
        return True

    @property
    def path(self):
        parts = []
        d = self
        while d is not None:
            parts.append(d.name or "companion object")
            d = d.owner
        return ".".join(reversed(parts))

    @property
    def type(self):
        head = self.head
        depth = 0
        for i, c in enumerate(head):
            if c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
            elif c == ":" and depth == 0 and i > 0:
                return head[i + 1:].strip()
        return ""

    @property
    def member(self):
        head = self.head
        for m in self.modifiers:
            head = re.sub(r"^" + m + r"\s+", "", head)
        head = re.sub(r"^(fun|val|var)\s+", "", head)
        depth = 0
        for i, c in enumerate(head):
            if c == "(":
                depth += 1
            elif c == ")":
                depth -= 1
            elif c == ":" and depth == 0:
                return head[:i].strip()
        return head.strip()


def scan_kotlin(text):
    raw = text.split("\n")
    stripped = [strip_literals(l) for l in raw]
    n = len(raw)
    decls = []
    stack = []
    depth = 0
    i = 0
    last_property = None

    def body_depth():
        return stack[-1][1] if stack else 0

    def collect(start):
        j = start
        stmt_raw = raw[j].strip()
        stmt_s = stripped[j].strip()
        while (paren_balance(stmt_s) > 0 or stmt_s.endswith(CONTINUATION)) and j + 1 < n:
            j += 1
            stmt_raw += " " + raw[j].strip()
            stmt_s += " " + stripped[j].strip()
        return stmt_raw, stmt_s, j

    def single_return(after):
        k = after + 1
        while k < n and not stripped[k].strip():
            k += 1
        if k + 1 < n and stripped[k].strip().startswith("return ") and stripped[k + 1].strip() == "}":
            return collapse(raw[k].strip()[len("return "):])
        return None

    while i < n:
        s = stripped[i].strip()
        at_body = depth == body_depth()
        consumed_to = i
        if at_body and s and not s.startswith("@"):
            cm = CLASS_RE.match(s)
            mm = MEMBER_RE.match(s) if not cm else None
            if cm:
                stmt_raw, stmt_s, consumed_to = collect(i)
                head, _ = cut_head(stmt_raw)
                mods = cm.group(1).split()
                kind = cm.group(2)
                if "companion" in mods:
                    kind = "companion object"
                elif "enum" in mods:
                    kind = "enum class"
                decl = Decl(kind, cm.group(3), collapse(head), mods, stack[-1][0] if stack else None, i + 1)
                decls.append(decl)
                if decl.owner is not None:
                    decl.owner.children.append(decl)
                before = depth
                for k in range(i, consumed_to + 1):
                    depth += stripped[k].count("{") - stripped[k].count("}")
                if "{" in stmt_s and depth > before:
                    stack.append((decl, before + 1))
                last_property = None
                i = consumed_to + 1
                continue
            if mm:
                stmt_raw, stmt_s, consumed_to = collect(i)
                head, tail = cut_head(stmt_raw)
                mods = mm.group(1).split()
                kind = mm.group(2)
                if kind == "init":
                    for k in range(i, consumed_to + 1):
                        depth += stripped[k].count("{") - stripped[k].count("}")
                    i = consumed_to + 1
                    continue
                if "const" in mods:
                    kind = "const val"
                name_m = re.match(r"(?:" + MOD_RE + r")(?:fun|val|var)\s+(?:<[^>]*>\s*)?([A-Za-z_][A-Za-z0-9_]*)", head)
                name = name_m.group(1) if name_m else ("constructor" if kind == "constructor" else head)
                decl = Decl(kind, name, collapse(head), mods, stack[-1][0] if stack else None, i + 1)
                if decl.owner is not None:
                    decl.owner.children.append(decl)
                decls.append(decl)
                if tail is not None:
                    decl.definition = collapse(tail)
                elif stmt_s.rstrip().endswith("{"):
                    decl.block = True
                    decl.definition = single_return(consumed_to)
                for k in range(i, consumed_to + 1):
                    depth += stripped[k].count("{") - stripped[k].count("}")
                last_property = decl if kind in ("val", "var") and tail is None else None
                i = consumed_to + 1
                continue
            if s.startswith("get()") and last_property is not None:
                stmt_raw, stmt_s, consumed_to = collect(i)
                if stmt_s.startswith("get() ="):
                    last_property.definition = collapse(stmt_raw[len("get() ="):])
                elif stmt_s.startswith("get() {"):
                    last_property.block = True
                    last_property.definition = single_return(consumed_to)
                for k in range(i, consumed_to + 1):
                    depth += stripped[k].count("{") - stripped[k].count("}")
                i = consumed_to + 1
                last_property = None
                continue
            if stack and stack[-1][0].kind == "enum class" and re.match(r"^[A-Z0-9_]+(\s*,\s*[A-Z0-9_]+)*\s*[,;]?$", s):
                stack[-1][0].entries.extend(t for t in re.split(r"[,\s;]+", s) if t)
        depth += stripped[i].count("{") - stripped[i].count("}")
        if depth != body_depth() and not (stack and stack[-1][0].kind == "enum class"):
            last_property = last_property if depth > body_depth() else None
        while stack and depth < stack[-1][1]:
            stack.pop()
            last_property = None
        i = consumed_to + 1
    return decls


def external_roots(imports):
    roots = set()
    for imp in imports:
        if imp.startswith(INTERNAL_ROOT + "."):
            continue
        seg = imp.split(".")
        roots.add(".".join(seg[:2]) if len(seg) >= 2 else imp)
    return sorted(roots)


def kotlin_files(paths):
    return [p for p in paths if p.endswith(".kt")]


def source_set_of(path):
    m = re.match(r"src/(\w+)/", path)
    return m.group(1) if m else ""


def kotlin_row(path):
    text = read_text(path)
    nr = nr_lines(read_bytes(path))
    pkg_m = re.search(r"(?m)^\s*package\s+([\w.]+)", text)
    pkg = pkg_m.group(1) if pkg_m else ""
    imports = re.findall(r"(?m)^\s*import\s+([\w.]+)", text)
    stripped = "\n".join(strip_literals(l) for l in text.split("\n"))
    decls = len(DECL_RE.findall(stripped))
    tests = len(re.findall(r"(?m)^\s*@Test\b", text))
    return [code(path), nr, code(pkg), len(imports), decls, tests, ", ".join(external_roots(imports))]


def gen_kotlin_md(paths):
    out = ["# Kotlin file reference", "", NOTE, ""]
    out.append(
        "Every Kotlin file with hard metadata extracted from its text: line count, package, import count, "
        "declaration count (`Decls`, regex-based after stripping string literals: classes, objects, interfaces, "
        "functions, properties and local variables), `@Test` count, and the external import roots it depends on "
        f"(imports under `{INTERNAL_ROOT}` are project-internal and omitted). For the declaration names, see "
        "[`public-api.md`](public-api.md) or the file itself."
    )
    for source_set in SOURCE_SETS:
        files = [p for p in kotlin_files(paths) if source_set_of(p) == source_set]
        if not files:
            continue
        out += ["", f"## `{source_set}` Kotlin files ({len(files)})", ""]
        rows = [kotlin_row(p) for p in files]
        out.append(table(["File", "Lines", "Package", "Imports", "Decls", "Tests", "External import roots"], rows,
                         ["---", "---:", "---", "---:", "---:", "---:", "---"]))
    return "\n".join(out) + "\n"


def yml_meta(path, text):
    if not HAVE_YAML:
        return "GitHub Actions workflow (install PyYAML for details)"
    data = yaml.safe_load(text) or {}
    on = data.get("on", data.get(True))
    if isinstance(on, dict):
        triggers = ", ".join(code(k) for k in on)
    elif isinstance(on, list):
        triggers = ", ".join(code(k) for k in on)
    else:
        triggers = code(on)
    jobs = ", ".join(code(j) for j in (data.get("jobs") or {}))
    return f"workflow {code(data.get('name', ''))}; triggers: {triggers}; jobs: {jobs}"


def toml_sections(text):
    sections = {}
    current = None
    for line in text.split("\n"):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        m = re.match(r"^\[(\w+)\]$", line)
        if m:
            current = m.group(1)
            sections[current] = []
            continue
        m = re.match(r"^([\w-]+)\s*=\s*(.+)$", line)
        if m and current is not None:
            sections[current].append((m.group(1), m.group(2)))
    return sections


def toml_meta(path, text):
    sections = toml_sections(text)
    parts = []
    for name, entries in sections.items():
        parts.append(f"[{name}]: " + ", ".join(code(k) for k, _ in entries))
    return "; ".join(parts)


def kts_meta(path, text):
    parts = []
    root = re.search(r'rootProject\.name\s*=\s*"([^"]+)"', text)
    if root:
        parts.append(f"root project {code(root.group(1))}")
    plugins = re.findall(r'alias\(libs\.plugins\.([\w.]+)\)', text) + re.findall(r'id\("([^"]+)"\)', text)
    if plugins:
        parts.append("plugins: " + ", ".join(code(p) for p in plugins))
    blocks = re.findall(r"(?m)^(\w+)\s*\{", text)
    if blocks:
        parts.append("top-level blocks: " + ", ".join(code(b) for b in blocks))
    return "; ".join(parts)


def properties_meta(path, text):
    keys = [l.split("=", 1)[0].strip() for l in text.split("\n") if "=" in l and not l.strip().startswith("#")]
    return "keys: " + ", ".join(code(k) for k in keys)


def md_meta(path, text):
    headings = re.findall(r"(?m)^(#{1,6})\s+(.+)$", text)
    first = next((h[1] for h in headings if h[0] == "#"), "")
    parts = text.split("\n\n")
    generated = "generated" if len(parts) > 1 and parts[1].startswith(NOTE[:34]) else "hand-maintained"
    regions = len(set(m.group(1) for m in REGION_RE.finditer(text)))
    extra = f"; {regions} generated region(s)" if regions else ""
    return f"{len(headings)} headings; title {code(first)}; {generated}{extra}"


def snapshot_stats(text):
    total = 0
    members = 0
    groups = 0
    for line in text.split("\n"):
        if line.startswith("total\t"):
            total = int(line.split("\t")[1])
        elif line.startswith("member\t"):
            members += 1
        elif line.startswith("group\t"):
            groups += 1
    return total, members, groups


def snapshot_meta(path, text):
    total, members, groups = snapshot_stats(text)
    return f"snapshot: {total} values, {members} members, {groups} groups"


def gitignore_meta(path, text):
    patterns = [l for l in text.split("\n") if l.strip() and not l.startswith("#")]
    return f"{len(patterns)} ignore patterns"


def py_meta(path, text):
    return f"{len(re.findall(r'(?m)^def ', text))} top-level functions"


def non_kotlin_meta(path):
    data = read_bytes(path)
    if is_binary(data):
        return "binary"
    text = data.decode("utf-8", "replace")
    ext = ext_of(path)
    name = os.path.basename(path)
    if path.startswith(SNAPSHOT_DIR + "/"):
        return snapshot_meta(path, text)
    if ext in (".yml", ".yaml"):
        return yml_meta(path, text)
    if ext == ".toml":
        return toml_meta(path, text)
    if ext == ".kts":
        return kts_meta(path, text)
    if ext == ".properties":
        return properties_meta(path, text)
    if ext == ".md":
        return md_meta(path, text)
    if ext == ".py":
        return py_meta(path, text)
    if name == ".gitignore":
        return gitignore_meta(path, text)
    if name == "gradlew":
        return "Gradle wrapper shell script"
    if name == "gradlew.bat":
        return "Gradle wrapper batch script"
    return ""


