def gradle_facts():
    text = read_text("build.gradle.kts")
    facts = {}

    def search(pattern, flags=0):
        m = re.search(pattern, text, flags)
        return m.group(1) if m else ""

    facts["plugins"] = re.findall(r"alias\(libs\.plugins\.([\w.]+)\)", text)
    facts["group"] = search(r'(?m)^group\s*=\s*"([^"]+)"')
    facts["version"] = search(r'(?m)^version\s*=\s*"([^"]+)"')
    facts["toolchain"] = search(r"jvmToolchain\((\d+)\)")
    facts["jvmTarget"] = search(r"JvmTarget\.(JVM_\w+)")
    facts["targets"] = re.findall(
        r"(?m)^\s*(jvm|androidTarget|iosArm64|iosSimulatorArm64|iosX64|macosArm64|macosX64|linuxX64|linuxArm64|"
        r"mingwX64|watchosArm64|watchosSimulatorArm64|watchosX64|tvosArm64|tvosSimulatorArm64|tvosX64|js|wasmJs)\s*[({]",
        text,
    )
    facts["hierarchy"] = "applyDefaultHierarchyTemplate()" in text
    deps = []
    for source_set, body in re.findall(r"(\w+)\.dependencies\s*\{([^}]*)\}", text, re.S):
        for conf, lib in re.findall(r"(api|implementation|compileOnly|runtimeOnly)\(libs\.([\w.]+)\)", body):
            deps.append((source_set, conf, lib))
    facts["deps"] = deps
    facts["tasks"] = re.findall(r'tasks\.named<\w+>\("(\w+)"\)', text)
    facts["snapshotProperty"] = search(r'providers\.gradleProperty\("(updateSnapshots)"\)')
    facts["snapshotSystemProperty"] = search(r'systemProperty\("([\w.]+)"')
    facts["versionSystemProperty"] = search(r'systemProperty\("([\w.]+)",\s*project\.version')
    idx = text.find("coordinates(")
    facts["coordinates"] = collapse(balanced(text, idx + len("coordinates"))) if idx >= 0 else ""
    idx = text.find("configure(")
    facts["configure"] = collapse(balanced(text, idx + len("configure"))) if idx >= 0 else ""
    facts["central"] = "publishToMavenCentral(" in text
    facts["signing"] = search(r'if\s*\(providers\.gradleProperty\("(\w+)"\)\.isPresent\)\s*\{\s*signAllPublications\(\)')
    pom_idx = text.find("pom {")
    pom_block = brace_block(text, text.index("{", pom_idx)) if pom_idx >= 0 else ""
    cuts = [pom_block.find(name + " {") for name in ("licenses", "developers", "scm")]
    cuts = [c for c in cuts if c >= 0]
    head = pom_block[:min(cuts)] if cuts else pom_block

    def sub_block(name):
        i = pom_block.find(name + " {")
        return brace_block(pom_block, pom_block.index("{", i)) if i >= 0 else ""

    facts["pom"] = set_calls(head)
    facts["licenses"] = set_calls(sub_block("licenses"))
    facts["developers"] = set_calls(sub_block("developers"))
    facts["scm"] = set_calls(sub_block("scm"))
    return facts


def settings_facts():
    text = read_text("settings.gradle.kts")
    facts = {"root": "", "plugins": [], "pluginRepos": [], "repos": [], "mode": ""}
    m = re.search(r'rootProject\.name\s*=\s*"([^"]+)"', text)
    facts["root"] = m.group(1) if m else ""
    facts["plugins"] = re.findall(r'id\("([^"]+)"\)\s*version\s*"([^"]+)"', text)
    pm = re.search(r"pluginManagement\s*\{(.*?)\n\}", text, re.S)
    facts["pluginRepos"] = re.findall(r"(\w+)\(\)", pm.group(1)) if pm else []
    dr = re.search(r"dependencyResolutionManagement\s*\{(.*?)\n\}", text, re.S)
    facts["repos"] = [r for r in re.findall(r"(\w+)\(\)", dr.group(1)) if r != "set"] if dr else []
    mode = re.search(r"RepositoriesMode\.(\w+)", text)
    facts["mode"] = mode.group(1) if mode else ""
    return facts


def properties_pairs(path):
    pairs = []
    for line in read_text(path).split("\n"):
        if "=" in line and not line.strip().startswith("#"):
            k, v = line.split("=", 1)
            pairs.append((k.strip(), v.strip()))
    return pairs


def render_workflow(path):
    data = yaml.safe_load(read_text(path)) or {}
    out = [f"### `{path}`", ""]
    on = data.get("on", data.get(True))
    if isinstance(on, dict):
        triggers = []
        for k, v in on.items():
            if isinstance(v, dict) and v:
                details = "; ".join(f"{kk}: {', '.join(code(x) for x in (vv if isinstance(vv, list) else [vv]))}" for kk, vv in v.items())
                triggers.append(f"{code(k)} ({details})")
            else:
                triggers.append(code(k))
        trigger_text = ", ".join(triggers)
    elif isinstance(on, list):
        trigger_text = ", ".join(code(k) for k in on)
    else:
        trigger_text = code(on)
    rows = [["Workflow name", code(data.get("name", ""))], ["Triggers", trigger_text]]
    perms = data.get("permissions")
    if perms:
        rows.append(["Permissions", ", ".join(f"{code(k)}: {code(v)}" for k, v in perms.items()) if isinstance(perms, dict) else code(perms)])
    conc = data.get("concurrency")
    if conc:
        rows.append(["Concurrency", ", ".join(f"{k}: {code(yaml_scalar(v))}" for k, v in conc.items()) if isinstance(conc, dict) else code(conc)])
    out += [table(["Workflow fact", "Value"], rows), ""]
    for job_id, job in (data.get("jobs") or {}).items():
        out += [f"#### Job `{job_id}`", ""]
        rows = [["Name", code(job.get("name", job_id))], ["Runs on", code(job.get("runs-on", ""))]]
        if "timeout-minutes" in job:
            rows.append(["Timeout (minutes)", code(job["timeout-minutes"])])
        if "needs" in job:
            rows.append(["Needs", code(job["needs"])])
        if "permissions" in job and isinstance(job["permissions"], dict):
            rows.append(["Permissions", ", ".join(f"{code(k)}: {code(v)}" for k, v in job["permissions"].items())])
        strategy = job.get("strategy") or {}
        if "fail-fast" in strategy:
            rows.append(["Fail fast", code(yaml_scalar(strategy["fail-fast"]))])
        out += [table(["Job fact", "Value"], rows), ""]
        matrix = (strategy.get("matrix") or {}).get("include")
        if matrix:
            keys = []
            for entry in matrix:
                for k in entry:
                    if k not in keys:
                        keys.append(k)
            out += ["Matrix:", "", table(keys, [[code(yaml_scalar(e.get(k, ""))) for k in keys] for e in matrix]), ""]
        rows = []
        for step in job.get("steps") or []:
            if "uses" in step:
                with_ = step.get("with") or {}
                params = ", ".join(f"{k}={code(yaml_scalar(v))}" for k, v in with_.items())
                action = code(step["uses"]) + (f" ({params})" if params else "")
            else:
                run = str(step.get("run", "")).strip().split("\n")[0]
                action = "run: " + code(run)
            name = step.get("name") or (step.get("uses") or "run")
            cond = step.get("if")
            if cond:
                name = f"{name} (if {code(cond)})"
            env = step.get("env") or {}
            if env:
                action += "; env: " + ", ".join(code(k) for k in env)
            rows.append([name, action])
        out += [table(["Step", "Action / command"], rows), ""]
    return "\n".join(out)


